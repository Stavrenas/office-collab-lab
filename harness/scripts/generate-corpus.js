/**
 * Generate a small, legally trivial OOXML corpus for round-trip tests.
 * Run from harness/: node scripts/generate-corpus.js
 */
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { execFileSync } = require("child_process");

const corpusRoot = path.resolve(__dirname, "../../corpus");
fs.mkdirSync(corpusRoot, { recursive: true });

function writeXmlTree(dir, files) {
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  for (const [rel, content] of Object.entries(files)) {
    const full = path.join(dir, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, content);
  }
}

function zipDir(sourceDir, outFile) {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  if (fs.existsSync(outFile)) fs.unlinkSync(outFile);
  execFileSync("zip", ["-qr", outFile, "."], { cwd: sourceDir });
}

function sha256File(file) {
  return crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
}

