const manifest = [];
for (const file of fs.readdirSync(corpusRoot).filter((f) => !f.startsWith("."))) {
  const full = path.join(corpusRoot, file);
  if (!fs.statSync(full).isFile()) continue;
  manifest.push({
    file,
    bytes: fs.statSync(full).size,
    sha256: sha256File(full),
  });
}
fs.writeFileSync(path.join(corpusRoot, "MANIFEST.json"), JSON.stringify(manifest, null, 2));
